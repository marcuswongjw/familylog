// Public deployment identifiers only. Secrets stay in Script Properties / Secret Manager.
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const firebaseFields=['apiKey','authDomain','projectId','storageBucket','messagingSenderId','appId','measurementId'];
function readProjectConfig(file=path.join(root,'config/project.json')){
 const value=JSON.parse(fs.readFileSync(file,'utf8'));
 if(value.schema!==1||!/^[-\w]{20,}$/.test(value.spreadsheetId)||!/^[-\w@.]+$/.test(value.calendarId))throw Error('Invalid spreadsheet/calendar configuration');
 if(!value.firebase||firebaseFields.some(key=>typeof value.firebase[key]!=='string'||!value.firebase[key])||Object.keys(value.firebase).some(key=>!firebaseFields.includes(key))||!/^[-\w]{80,}$/.test(value.vapidKey))throw Error('Invalid public Firebase configuration');
 if(value.firebase.authDomain!==value.firebase.projectId+'.firebaseapp.com'||![value.firebase.projectId+'.firebasestorage.app',value.firebase.projectId+'.appspot.com'].includes(value.firebase.storageBucket))throw Error('Firebase service identities do not match');
 for(const name of ['family','parents']){
  const service=value.services?.[name];
  if(!/^[-\w]{20,}$/.test(service?.scriptId)||!/^AKfy[-\w]+$/.test(service?.deploymentId))throw Error('Invalid '+name+' service identity');
  const url=new URL(value.sites?.[name]);if(url.protocol!=='https:'||url.username||url.password||url.search||url.hash||url.pathname!=='/')throw Error('Invalid '+name+' site URL');
 }
 if(value.services.family.scriptId===value.services.parents.scriptId||value.services.family.deploymentId===value.services.parents.deploymentId)throw Error('Family and parents must have separate service identities');
 return value;
}
function serviceConfig(name,config=readProjectConfig()){
 if(!['family','parents'].includes(name))throw Error('Unknown service');
 return {...config.services[name],url:'https://script.google.com/macros/s/'+config.services[name].deploymentId+'/exec'};
}
function publicConfig(config=readProjectConfig()){
 return {firebase:Object.fromEntries(firebaseFields.map(key=>[key,config.firebase[key]])),vapidKey:config.vapidKey,sites:config.sites,endpoints:{family:serviceConfig('family',config).url,parents:serviceConfig('parents',config).url}};
}
function gasConfigSource(service,config=readProjectConfig()){
 const settings={service,spreadsheetId:config.spreadsheetId,calendarId:config.calendarId,firebaseApiKey:config.firebase.apiKey,familyUrl:serviceConfig('family',config).url,parentsUrl:serviceConfig('parents',config).url};
 // A hoisted function avoids Apps Script file evaluation-order dependencies.
 return '// Generated by scripts/project-config.cjs; edit config/project.json.\nfunction deploymentSettings_() { return '+JSON.stringify(settings)+'; }\n';
}
function generatedFiles(config=readProjectConfig()){
 return {'js/project-config.js':'// Generated by scripts/project-config.cjs; edit config/project.json.\nconst NEST_PUBLIC_CONFIG = '+JSON.stringify(publicConfig(config),null,2)+';\n','gas/deployment.js':gasConfigSource('parents',config),'.clasp.json':JSON.stringify({...config.services.parents,rootDir:'.'},(key,value)=>key==='deploymentId'?undefined:value,2)+'\n'};
}
function checkGenerated(config=readProjectConfig()){
 for(const [name,source] of Object.entries(generatedFiles(config)))if(!fs.existsSync(path.join(root,name))||fs.readFileSync(path.join(root,name),'utf8')!==source)throw Error(name+' is stale. Run npm run config:generate.');
 const manifest=JSON.parse(fs.readFileSync(path.join(root,'appsscript.json'),'utf8'));
 if(manifest.timeZone!=='Asia/Singapore')throw Error('Apps Script must use the family timezone');
 const firebase=JSON.parse(fs.readFileSync(path.join(root,'.firebaserc'),'utf8'));
 if(firebase.projects.default!==config.firebase.projectId)throw Error('Firebase deployment project does not match project configuration');
 return config;
}
if(require.main===module){
 const config=readProjectConfig();if(process.argv.includes('--check'))checkGenerated(config);
 else for(const [name,source] of Object.entries(generatedFiles(config)))fs.writeFileSync(path.join(root,name),source);
}
module.exports={readProjectConfig,serviceConfig,publicConfig,gasConfigSource,checkGenerated};
